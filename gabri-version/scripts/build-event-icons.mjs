/**
 * Writes src/lib/eventIconPaths.ts: SVG path data (24x24, lucide) for each event type's map icon,
 * so the maps can draw icons on a canvas without React. Run: node scripts/build-event-icons.mjs
 */
import { writeFileSync } from "node:fs";

const ICONS = {
  sports_play: "volleyball", sports_watch: "trophy", career: "briefcase-business", academic: "book-open",
  usc: "landmark", student: "users-round", community: "globe", class: "graduation-cap",
};
const n = (v) => Number(v);
function toPath([tag, a]) {
  if (tag === "path") return a.d;
  if (tag === "circle") { const [cx, cy, r] = [n(a.cx), n(a.cy), n(a.r)]; return `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`; }
  if (tag === "ellipse") { const [cx, cy, rx, ry] = [n(a.cx), n(a.cy), n(a.rx), n(a.ry)]; return `M${cx - rx} ${cy}a${rx} ${ry} 0 1 0 ${2 * rx} 0a${rx} ${ry} 0 1 0 ${-2 * rx} 0`; }
  if (tag === "line") return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
  if (tag === "polyline" || tag === "polygon") { const p = a.points.trim().split(/[\s,]+/).map(Number); let d = `M${p[0]} ${p[1]}`; for (let i = 2; i < p.length; i += 2) d += `L${p[i]} ${p[i + 1]}`; return tag === "polygon" ? d + "Z" : d; }
  if (tag === "rect") {
    const [x, y, w, h] = [n(a.x ?? 0), n(a.y ?? 0), n(a.width), n(a.height)]; const r = Math.min(n(a.rx ?? 0), w / 2, h / 2);
    return r ? `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}Z` : `M${x} ${y}h${w}v${h}h${-w}Z`;
  }
  throw new Error(`unsupported ${tag}`);
}
const out = {};
for (const [cat, name] of Object.entries(ICONS)) {
  const { __iconData } = await import(new URL(`../node_modules/lucide-react/dist/esm/icons/${name}.mjs`, import.meta.url));
  out[cat] = __iconData.node.map(toPath);
}
writeFileSync(new URL("../src/lib/eventIconPaths.ts", import.meta.url),
  `/** Generated by scripts/build-event-icons.mjs from lucide icons (ISC). 24x24 stroke paths per event type. */\nexport const EVENT_ICON_PATHS: Record<string, string[]> = ${JSON.stringify(out, null, 2)};\n`);
console.log("wrote", Object.keys(out).length, "icons");
